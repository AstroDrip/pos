import { storeDay } from '../core/store-time';
import { formatSar } from '../core/money';
import { computeInvoice } from '../core/vat';

/** Small backwards clock adjustments (Windows time sync) are tolerated. */
const CLOCK_TOLERANCE_MS = 10 * 60_000;
import { appendAudit } from './audit';
import { getProduct } from './catalog';
import { DomainError, type Ctx } from './context';
import { applyMovement } from './inventory';
import { postEntry } from './ledger';
import { hasPermission, requirePermission } from './users';

export interface SaleLineInput {
  productId: number;
  qty: number; // milli-units
  discount?: number; // halalas off this line
  /** The unit price the cashier saw. If the shelf price changed since, the sale is refused (BUG-001). */
  expectedUnitPrice?: number;
}

export interface PaymentInput {
  tender: 'cash' | 'card';
  amount: number;
  reference?: string;
}

export interface SaleInput {
  /** Generated by the till once per bill. Re-sending the same key returns the same sale, never a second one. */
  idempotencyKey: string;
  lines: SaleLineInput[];
  payments: PaymentInput[];
  customerId?: number;
  /** Supervisor who approved discounts, when the cashier lacks sale.discount. */
  discountApproverId?: number;
}

export interface SaleResult {
  saleId: number;
  invoiceNo: string;
  uuid: string;
  totalIncl: number;
  totalVat: number;
  changeGiven: number;
  createdAt: string;
  replayed: boolean; // true when this was a retry of an already-finalized sale
  negativeStockProducts: number[];
}

/**
 * Finalizes a sale in ONE transaction: invoice number, sale, lines (snapshotted), payments,
 * stock movements, journal entry and audit row. Either everything commits or nothing does.
 */
export function finalizeSale(ctx: Ctx, userId: number, input: SaleInput): SaleResult {
  requirePermission(ctx, userId, 'sale.create');
  if (!/^[\w-]{8,64}$/.test(input.idempotencyKey)) throw new DomainError('VALIDATION', 'Invalid idempotency key');
  if (input.lines.length === 0) throw new DomainError('VALIDATION', 'Sale has no items');
  if (input.lines.length > 500) throw new DomainError('VALIDATION', 'Too many lines');

  return ctx.db.transaction((): SaleResult => {
    const existing = ctx.db.prepare('SELECT id FROM sales WHERE idempotency_key = ?').get(input.idempotencyKey) as { id: number } | undefined;
    if (existing) return { ...getSaleResult(ctx, existing.id), replayed: true };

    const shift = ctx.db.prepare("SELECT id FROM register_shifts WHERE status = 'open'").get() as { id: number } | undefined;
    if (!shift) throw new DomainError('NO_OPEN_SHIFT', 'Open a shift before selling');

    // Discounts need permission, either the cashier's own or a supervisor's approval.
    const hasDiscount = input.lines.some((l) => (l.discount ?? 0) > 0);
    let approver: number | null = null;
    if (hasDiscount && !hasPermission(ctx, userId, 'sale.discount')) {
      if (input.discountApproverId === undefined || !hasPermission(ctx, input.discountApproverId, 'sale.discount')) {
        throw new DomainError('PERMISSION_DENIED', 'Discount needs supervisor approval');
      }
      approver = input.discountApproverId;
    }

    // The clock must not run backwards: invoice dates would go out of order (BUG-009).
    const last = ctx.db.prepare('SELECT created_at FROM sales ORDER BY id DESC LIMIT 1').get() as { created_at: string } | undefined;
    if (last && Date.parse(ctx.now()) < Date.parse(last.created_at) - CLOCK_TOLERANCE_MS) {
      throw new DomainError('CLOCK_WRONG', `The computer clock is earlier than the last sale (${last.created_at}). Fix the Windows date and time before selling.`);
    }

    // Snapshot product data at sale time.
    const products = input.lines.map((l) => {
      const p = getProduct(ctx, l.productId);
      if (!p || !p.active) throw new DomainError('NOT_FOUND', `Product ${l.productId} not available`);
      if (l.expectedUnitPrice !== undefined && l.expectedUnitPrice !== p.priceIncl) {
        throw new DomainError('PRICE_CHANGED', `The price of ${p.nameEn} changed from ${formatSar(l.expectedUnitPrice)} to ${formatSar(p.priceIncl)}. Check the new price with the customer.`);
      }
      if (!Number.isSafeInteger(l.qty) || l.qty <= 0) throw new DomainError('VALIDATION', 'Quantity must be positive');
      if (p.sellMode === 'unit' && l.qty % 1000 !== 0) throw new DomainError('VALIDATION', `${p.nameEn} is sold by whole units`);
      return p;
    });

    let totals;
    try {
      totals = computeInvoice(
        input.lines.map((l, i) => ({ unitPriceIncl: products[i]!.priceIncl, qty: l.qty, discount: l.discount ?? 0, vatRate: products[i]!.vatRateBp })),
      );
    } catch (e) {
      throw new DomainError('VALIDATION', (e as Error).message);
    }

    // Payments: card cannot exceed the total; change comes only from cash.
    for (const p of input.payments) {
      if (!Number.isSafeInteger(p.amount) || p.amount <= 0) throw new DomainError('VALIDATION', 'Payment amounts must be positive');
    }
    const cash = input.payments.filter((p) => p.tender === 'cash').reduce((s, p) => s + p.amount, 0);
    const card = input.payments.filter((p) => p.tender === 'card').reduce((s, p) => s + p.amount, 0);
    if (card > totals.totalIncl) throw new DomainError('VALIDATION', 'Card amount is more than the bill');
    const paid = cash + card;
    if (paid < totals.totalIncl) throw new DomainError('INSUFFICIENT_PAYMENT', 'Payment is less than the total');
    const change = paid - totals.totalIncl;
    if (change > cash) throw new DomainError('VALIDATION', 'Change can only be given from cash');

    const n = (ctx.db.prepare("UPDATE invoice_counters SET next_value = next_value + 1 WHERE series = 'SALE' RETURNING next_value - 1 AS v").get() as { v: number }).v;
    const invoiceNo = `INV-${String(n).padStart(8, '0')}`;
    const uuid = ctx.uuid();
    const createdAt = ctx.now();

    const saleId = Number(
      ctx.db
        .prepare(
          `INSERT INTO sales (invoice_no, uuid, idempotency_key, shift_id, user_id, customer_id, total_incl, total_vat, total_excl,
             total_discount, paid_total, change_given, discount_approved_by, created_at)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
        )
        .run(invoiceNo, uuid, input.idempotencyKey, shift.id, userId, input.customerId ?? null, totals.totalIncl, totals.totalVat,
          totals.totalExcl, totals.totalDiscount, paid, change, approver, createdAt).lastInsertRowid,
    );

    const insertLine = ctx.db.prepare(
      `INSERT INTO sale_lines (sale_id, line_no, product_id, name_ar, name_en, qty, unit_price_incl, discount, vat_rate_bp,
         line_incl, line_vat, line_excl, unit_cost) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
    );
    let cogs = 0;
    const negative: number[] = [];
    totals.lines.forEach((t, i) => {
      const p = products[i]!;
      const mv = applyMovement(ctx, { productId: p.id, qty: -input.lines[i]!.qty, reason: 'sale', sourceType: 'sale', sourceId: saleId, sourceLine: i + 1, userId });
      if (mv.wentNegative) negative.push(p.id);
      cogs += -mv.value;
      insertLine.run(saleId, i + 1, p.id, p.nameAr, p.nameEn, input.lines[i]!.qty, p.priceIncl, t.discount, t.vatRate, t.lineIncl, t.lineVat, t.lineExcl, mv.unitCost);
    });

    const insertPay = ctx.db.prepare('INSERT INTO payments (sale_id, tender, amount, reference) VALUES (?, ?, ?, ?)');
    for (const p of input.payments) insertPay.run(saleId, p.tender, p.amount, p.reference ?? null);

    postEntry(ctx, {
      date: storeDay(createdAt),
      sourceType: 'sale',
      sourceId: saleId,
      memo: `Sale ${invoiceNo}`,
      lines: [
        { account: '1010', debit: cash - change },
        { account: '1020', debit: card },
        { account: '4000', credit: totals.totalExcl },
        { account: '2200', credit: totals.totalVat },
        { account: '5000', debit: cogs },
        { account: '1200', credit: cogs },
      ],
    });

    appendAudit(ctx, {
      userId,
      action: 'sale.finalize',
      entity: 'sale',
      entityId: saleId,
      details: { invoiceNo, total: totals.totalIncl, discount: totals.totalDiscount, approver, negativeStock: negative },
    });

    return { saleId, invoiceNo, uuid, totalIncl: totals.totalIncl, totalVat: totals.totalVat, changeGiven: change, createdAt, replayed: false, negativeStockProducts: negative };
  })();
}

function getSaleResult(ctx: Ctx, saleId: number): Omit<SaleResult, 'replayed'> {
  const s = ctx.db.prepare('SELECT id, invoice_no, uuid, total_incl, total_vat, change_given, created_at FROM sales WHERE id = ?').get(saleId) as {
    id: number; invoice_no: string; uuid: string; total_incl: number; total_vat: number; change_given: number; created_at: string;
  };
  return { saleId: s.id, invoiceNo: s.invoice_no, uuid: s.uuid, totalIncl: s.total_incl, totalVat: s.total_vat, changeGiven: s.change_given, createdAt: s.created_at, negativeStockProducts: [] };
}

export interface ReceiptData {
  invoiceNo: string;
  uuid: string;
  createdAt: string;
  cashier: string;
  lines: { nameAr: string; nameEn: string; qty: number; unitPriceIncl: number; discount: number; lineIncl: number; vatRateBp: number }[];
  totalExcl: number;
  totalVat: number;
  totalIncl: number;
  totalDiscount: number;
  payments: { tender: string; amount: number }[];
  changeGiven: number;
}

/** Receipt content comes only from the stored, immutable sale, so a reprint can never create a sale. */
export function receiptData(ctx: Ctx, saleId: number): ReceiptData {
  const s = ctx.db
    .prepare(
      `SELECT s.invoice_no, s.uuid, s.created_at, u.display_name AS cashier, s.total_excl, s.total_vat, s.total_incl,
              s.total_discount, s.change_given
       FROM sales s JOIN users u ON u.id = s.user_id WHERE s.id = ?`,
    )
    .get(saleId) as
    | { invoice_no: string; uuid: string; created_at: string; cashier: string; total_excl: number; total_vat: number; total_incl: number; total_discount: number; change_given: number }
    | undefined;
  if (!s) throw new DomainError('NOT_FOUND', 'Sale not found');
  return {
    invoiceNo: s.invoice_no,
    uuid: s.uuid,
    createdAt: s.created_at,
    cashier: s.cashier,
    lines: ctx.db
      .prepare('SELECT name_ar AS nameAr, name_en AS nameEn, qty, unit_price_incl AS unitPriceIncl, discount, line_incl AS lineIncl, vat_rate_bp AS vatRateBp FROM sale_lines WHERE sale_id = ? ORDER BY line_no')
      .all(saleId) as ReceiptData['lines'],
    totalExcl: s.total_excl,
    totalVat: s.total_vat,
    totalIncl: s.total_incl,
    totalDiscount: s.total_discount,
    payments: ctx.db.prepare('SELECT tender, amount FROM payments WHERE sale_id = ? ORDER BY id').all(saleId) as ReceiptData['payments'],
    changeGiven: s.change_given,
  };
}
