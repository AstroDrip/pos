// Copies migrations/*.sql into a TypeScript file, so the demo database can set itself up on a host
// without reading files from disk. Run after adding a migration: npm run demo:migrations
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(import.meta.dirname, '..', 'migrations');
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort().map((name) => ({ name, sql: readFileSync(join(dir, name), 'utf8') }));
const out = `// Generated by scripts/bundle-migrations.mjs from migrations/*.sql. Do not edit by hand.\nimport type { MigrationFile } from '../migrate-core.ts';\n\nexport const MIGRATIONS: MigrationFile[] = ${JSON.stringify(files, null, 2)};\n`;
writeFileSync(join(import.meta.dirname, '..', 'src', 'server', 'demo', 'migrations.generated.ts'), out);
console.log(`bundled ${files.length} migrations`);
